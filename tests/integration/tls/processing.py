import ssl
import sys
import time

# Keep this source-tree test import free of generated bytecode artifacts.
sys.dont_write_bytecode = True
from exercise import connect, server
from wire_response import response
from wire_response_tests import check_oracle

if not __debug__:
  raise RuntimeError('TLS processing tests require assertions enabled')


# /////////////////////////////////////////////////////////////////////////////
# +---------------------------------------------------------------------------+
# | [>] request                                                  ( function ) |
# +---------------------------------------------------------------------------+
# /////////////////////////////////////////////////////////////////////////////
def request(path, close=False):
  return (f'GET {path} HTTP/1.1\r\nHost: localhost\r\n' +
          ('Connection: close\r\n' if close else '') + '\r\n').encode()


# /////////////////////////////////////////////////////////////////////////////
# +---------------------------------------------------------------------------+
# | [>] main                                                  ( entry-point ) |
# +---------------------------------------------------------------------------+
# /////////////////////////////////////////////////////////////////////////////
def main():
  check_oracle()
  for version in (ssl.TLSVersion.TLSv1_2, ssl.TLSVersion.TLSv1_3):
    with server(mode='http-async', bio=127) as port:
      # /gated cannot finish until a later synchronous request on this same
      # connection executes. This detects serialized admission without timing.
      with connect(port, version, alpn='http/1.1') as peer:
        peer.sendall(b''.join(request(p) for p in
                             ('/gated', '/wait/2', '/source', '/release')))
        with peer.makefile('rb') as stream:
          for expected in (b'gated', b'2', b's' * 32768, b'release'):
            assert response(stream) == (200, expected)
          peer.sendall(request('/state'))
          assert response(stream) == (200, b'2:2:0')
          # Ordered close must preserve the predecessor and the final reader.
          peer.sendall(request('/wait/3') + request('/source', close=True) +
                       request('/hello'))
          assert response(stream) == (200, b'3')
          assert response(stream) == (200, b's' * 32768)
          assert stream.read(1) == b''
      with connect(port, version, alpn='http/1.1') as peer:
        peer.sendall(request('/hello') + request('/fail'))
        with peer.makefile('rb') as stream:
          assert response(stream) == (200, b'hello')
          assert response(stream)[0] == 500
      # One sleeping connection cannot occupy the sole transport worker.
      slow = connect(port, version, alpn='http/1.1')
      try:
        slow.sendall(request('/sleep'))
        with connect(port, version, alpn='http/1.1') as fast:
          with fast.makefile('rb') as stream:
            deadline = time.monotonic() + 5
            while True:
              fast.sendall(request('/state'))
              state = response(stream)
              assert state[0] == 200
              if state[1].endswith(b':1'):
                break
              assert time.monotonic() < deadline, state
            fast.sendall(request('/hello'))
            assert response(stream) == (200, b'hello')
            slow.close()
            deadline = time.monotonic() + 5
            while True:
              fast.sendall(request('/state'))
              state = response(stream)
              if state[1].endswith(b':0'):
                break
              assert time.monotonic() < deadline, state
      finally:
        slow.close()
    # Stop must cancel a live timed frame while the TLS peer remains open.
    with server(mode='http-async', control=True) as (port, process):
      with connect(port, version, alpn='http/1.1') as slow:
        slow.sendall(request('/sleep'))
        with connect(port, version, alpn='http/1.1') as fast:
          with fast.makefile('rb') as stream:
            deadline = time.monotonic() + 5
            while True:
              fast.sendall(request('/state'))
              if response(stream)[1].endswith(b':1'):
                break
              assert time.monotonic() < deadline
        process.stdin.write('stop\n')
        process.stdin.flush()
        process.wait(timeout=10)
        assert process.returncode == 0
        assert process.stdout.readline() == 'LIVE 0\n'
        assert slow.recv(1) == b''
    print(f'{version.name}: ordered mixed/source, failure, '
          'cancel and stop PASS')


if __name__ == '__main__':
  main()
